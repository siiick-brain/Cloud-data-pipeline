-- Warehouse model: raw landing, staging, Kimball star (dw), gold marts, quality results and catalog.
CREATE SCHEMA raw;
CREATE SCHEMA staging;
CREATE SCHEMA dw;
CREATE SCHEMA gold;
CREATE SCHEMA quality;
CREATE SCHEMA governance;

-- raw: written by the Kafka consumer and the seed job
CREATE TABLE raw.order_events (
    event_id        uuid PRIMARY KEY,
    payload         jsonb NOT NULL,
    kafka_partition int,
    kafka_offset    bigint,
    received_at     timestamptz NOT NULL DEFAULT now(),
    load_date       date NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')::date
);

CREATE TABLE raw.customers (
    customer_id text PRIMARY KEY,
    full_name   text,
    email       text,
    city        text,
    address     text,
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE raw.products (
    product_id   text PRIMARY KEY,
    product_name text,
    category     text,
    list_price   numeric(10,2),
    updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE raw.stores (
    store_id   text PRIMARY KEY,
    store_name text,
    city       text,
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- dw: star schema
CREATE TABLE dw.dim_customer (
    customer_key int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  text NOT NULL,
    full_name    text,
    email        text,
    city         text,
    address      text,
    valid_from   timestamptz NOT NULL,
    valid_to     timestamptz NOT NULL DEFAULT '9999-12-31',
    is_current   boolean NOT NULL DEFAULT true,
    CHECK (valid_from < valid_to)
);

CREATE TABLE dw.dim_product (
    product_key  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   text NOT NULL UNIQUE,
    product_name text,
    category     text,
    list_price   numeric(10,2)
);

CREATE TABLE dw.dim_store (
    store_key  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id   text NOT NULL UNIQUE,
    store_name text,
    city       text
);

CREATE TABLE dw.dim_date (
    date_key    int PRIMARY KEY,
    full_date   date UNIQUE,
    year        smallint,
    quarter     smallint,
    month       smallint,
    month_name  text,
    day         smallint,
    day_of_week smallint,
    day_name    text,
    is_weekend  boolean
);

CREATE TABLE dw.fact_order_line (
    event_id     uuid PRIMARY KEY,
    order_id     text NOT NULL,
    line_number  smallint NOT NULL,
    customer_key int NOT NULL REFERENCES dw.dim_customer (customer_key),
    product_key  int NOT NULL REFERENCES dw.dim_product (product_key),
    store_key    int NOT NULL REFERENCES dw.dim_store (store_key),
    date_key     int NOT NULL REFERENCES dw.dim_date (date_key),
    quantity     int NOT NULL CHECK (quantity > 0),
    unit_price   numeric(10,2) NOT NULL,
    currency     char(3) NOT NULL,
    net_amount   numeric(12,2) NOT NULL,
    occurred_at  timestamptz NOT NULL,
    load_date    date NOT NULL,
    loaded_at    timestamptz NOT NULL DEFAULT now()
);

-- staging: ETL lands here first, then inserts into the fact with ON CONFLICT DO NOTHING
CREATE UNLOGGED TABLE staging.fact_order_line (
    event_id     uuid NOT NULL,
    order_id     text NOT NULL,
    line_number  smallint NOT NULL,
    customer_key int NOT NULL,
    product_key  int NOT NULL,
    store_key    int NOT NULL,
    date_key     int NOT NULL,
    quantity     int NOT NULL,
    unit_price   numeric(10,2) NOT NULL,
    currency     char(3) NOT NULL,
    net_amount   numeric(12,2) NOT NULL,
    occurred_at  timestamptz NOT NULL,
    load_date    date NOT NULL
);

-- gold: marts for dashboards, rebuilt one load_date at a time by the ELT DAG
CREATE TABLE gold.daily_sales (
    load_date   date NOT NULL,
    sale_date   date NOT NULL,
    store_id    text NOT NULL,
    order_lines int NOT NULL,
    units       int NOT NULL,
    revenue     numeric(14,2) NOT NULL,
    PRIMARY KEY (load_date, sale_date, store_id)
);

CREATE TABLE gold.product_sales (
    load_date  date NOT NULL,
    sale_date  date NOT NULL,
    product_id text NOT NULL,
    category   text,
    units      int NOT NULL,
    revenue    numeric(14,2) NOT NULL,
    PRIMARY KEY (load_date, sale_date, product_id)
);

CREATE TABLE quality.dq_results (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    run_id     text NOT NULL,
    dag_id     text,
    check_name text NOT NULL,
    table_name text NOT NULL,
    passed     boolean NOT NULL,
    observed   numeric,
    threshold  numeric,
    score      numeric(5,4) NOT NULL CHECK (score BETWEEN 0 AND 1),
    details    text,
    checked_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE governance.catalog (
    table_schema   text NOT NULL,
    table_name     text NOT NULL,
    column_name    text NOT NULL,
    data_type      text,
    owner          text,
    pii_tag        text NOT NULL DEFAULT 'none' CHECK (pii_tag IN ('none', 'email', 'name', 'address')),
    retention_days int,
    description    text,
    PRIMARY KEY (table_schema, table_name, column_name)
);

-- indexes
CREATE INDEX ON raw.order_events (load_date);
CREATE UNIQUE INDEX dim_customer_one_current ON dw.dim_customer (customer_id) WHERE is_current;
CREATE INDEX dim_customer_as_of ON dw.dim_customer (customer_id, valid_from, valid_to);
CREATE INDEX ON dw.fact_order_line (customer_key);
CREATE INDEX ON dw.fact_order_line (product_key);
CREATE INDEX ON dw.fact_order_line (store_key);
CREATE INDEX ON dw.fact_order_line (date_key);
CREATE INDEX ON dw.fact_order_line (load_date);
CREATE INDEX ON quality.dq_results (table_name, checked_at DESC);
